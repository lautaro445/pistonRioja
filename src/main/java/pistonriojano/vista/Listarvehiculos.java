private void configurarTabla() {

    DefaultTableModel modelo = new DefaultTableModel(
        new Object[][]{},
        new String[]{
            "Patente",
            "Marca",
            "Modelo",
            "Año",
            "Cliente",
            "Tipo",
            "Puertas",
            "Combustible",
            "Cilindrada"
        }
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    jTable1.setModel(modelo);
    jTable1.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);
}

private void cargarVehiculos() {

    DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
    modelo.setRowCount(0);

    VehiculoDAO dao = new VehiculoDAO();

    try {
        List<Vehiculos> lista = dao.listar();

        for (Vehiculos v : lista) {

            String cliente = "";

            if (v.getCliente() != null) {
                cliente = v.getCliente().getDni();
            }

            if (v instanceof Autos) {

                Autos auto = (Autos) v;

                modelo.addRow(new Object[]{
                    auto.getPatente(),
                    auto.getMarca(),
                    auto.getModelo(),
                    auto.getAnio(),
                    cliente,
                    "Auto",
                    auto.getCantidad_puertas(),
                    auto.getCombustible(),
                    "-"
                });

            } else if (v instanceof Motos) {

                Motos moto = (Motos) v;

                modelo.addRow(new Object[]{
                    moto.getPatente(),
                    moto.getMarca(),
                    moto.getModelo(),
                    moto.getAnio(),
                    cliente,
                    "Moto",
                    "-",
                    "-",
                    moto.getCilindrada()
                });
            }
        }

        if (lista.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay vehículos registrados.");
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error al cargar vehículos: " + e.getMessage()
        );
    }
}

    

